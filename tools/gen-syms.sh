#!/usr/bin/env bash
# Writes web/hd/syms.js: the memory addresses the 3D view reads, taken from
# pokered/poke<red|blue>.sym (made by the build). Run after building a changed game.
set -euo pipefail
cd "$(dirname "$0")/.."
GAME="${1:-red}"
SYM="pokered/poke$GAME.sym"
NAMES="wSpriteStateData1 wSpriteStateData2 wTileMap wOverworldMap wWalkCounter
wIsInBattle wCurMap wYCoord wXCoord wCurMapTileset wCurMapHeight wCurMapWidth
wTilesetBank wTilesetBlocksPtr wTilesetGfxPtr wToggleableObjectFlags
wToggleableObjectList wStatusFlags5 wJoyIgnore wShadowOAM SpriteSheetPointerTable"
{
  echo "// Generated by tools/gen-syms.sh from pokered.sym. Do not edit."
  echo "// [bank, address] for each symbol the 3D view uses."
  echo "export const SYM = {"
  for n in $NAMES; do
    line=$(grep -E "^[0-9a-f]+:[0-9a-f]+ $n\$" "$SYM") || { echo "missing symbol $n" >&2; exit 1; }
    bank=${line%%:*}; rest=${line#*:}; addr=${rest%% *}
    echo "  $n: [0x$bank, 0x$addr],"
  done
  echo "};"
} > web/hd/syms.js
echo "Wrote web/hd/syms.js"
